/// Operating-system key codes kept alongside the common [`Key`].
///
/// Most code should use [`Key`]. Use this when the exact operating-system code
/// is needed.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
#[non_exhaustive]
pub enum RawCode {
    Linux { evdev: u16 },
    Windows { scan_code: u32, virtual_key: u32, extended: bool },
}
